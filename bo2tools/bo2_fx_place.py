"""BO2 createfx placements -> H1 stand-in effects via bo2_fx_map.tsv (shared across BO2 maps).
Writes fx_place.txt ("effect x y z pitch yaw roll") and fx_imports.txt (donor zone, effect, materials; child effects
listed before parents is the caller's job for effects with children, e.g. mp_ca_behemoth light_glow_industrial).
usage: bo2_fx_place.py <createfx.tsv> <bo2_fx_map.tsv> <out dir>
createfx.tsv: the t6 exporter's lines "placed <type> <fx id> <fx path> x y z pitch yaw roll ..." (tab separated)."""
import sys, re, os
cf, mp, out = sys.argv[1:4]
rules = []
for l in open(mp):
    if not l.strip() or l.startswith('#'): continue
    p = l.rstrip('\n').split('\t'); rules.append((re.compile(p[0]), p[1], p[2], p[3] if len(p) > 3 else ''))
place = ['# effect x y z pitch yaw roll (BO2 createfx positions, stand-ins from bo2_fx_map.tsv)']; used = {}; miss = {}
for l in open(cf):
    p = l.rstrip('\n').split('\t')
    if len(p) < 10 or p[0] != 'placed': continue
    r = next((r for r in rules if r[0].search(p[2])), None)
    if not r: miss[p[2]] = miss.get(p[2], 0) + 1; continue
    place.append(f"{r[1]} {p[4]} {p[5]} {p[6]} {p[7]} {p[8]} {p[9]}"); used[r[1]] = r
os.makedirs(out, exist_ok=True)
open(os.path.join(out, 'fx_place.txt'), 'w').write('\n'.join(place) + '\n')
imp = ['# donor zone, effect, donor materials (generated by bo2_fx_place.py)']
if 'fx/misc/light_glow_industrial' in used: imp.append('mp_ca_behemoth fx/misc/light_dust cloud_dust_mote_2_cloud')
imp += [f"{r[2]} {e} {r[3]}".strip() for e, r in used.items()]
open(os.path.join(out, 'fx_imports.txt'), 'w').write('\n'.join(imp) + '\n')
print(f"{len(place) - 1} placements, {len(used)} effects; unmapped: {miss}")
